import { describe, expect, it } from 'vitest'

import { toDateString } from './date-string'
import { addMonths, addYears } from './add-months'

describe('addMonths', () => {
  const d = toDateString

  it.each([
    ['2026-01-15', 1, '2026-02-15', '通常の加算'],
    ['2026-01-15', 12, '2027-01-15', '12ヶ月で1年'],
    ['2026-06-15', -3, '2026-03-15', '負の数で過去へ'],
    ['2026-01-15', 0, '2026-01-15', 'ゼロは変化なし'],
  ])('%s に %d ヶ月 → %s（%s）', (input, months, expected) => {
    expect(addMonths(d(input), months)).toBe(d(expected))
  })

  describe('月末のクランプ（存在しない日付への対処）', () => {
    it.each([
      ['2026-03-31', -1, '2026-02-28', '3/31 の1ヶ月前は平年2月に収まらない → 2/28'],
      ['2024-03-31', -1, '2024-02-29', '同じ状況でもうるう年なら 2/29'],
      ['2026-01-31', 1, '2026-02-28', '1/31 の1ヶ月後は2月に収まらない → 2/28'],
      ['2026-05-31', 1, '2026-06-30', '5/31 の1ヶ月後は6月に収まらない → 6/30'],
      ['2026-01-30', 1, '2026-02-28', '1/30 も同様にクランプされる'],
      ['2026-01-29', 1, '2026-02-28', '1/29 も同様（平年）'],
      ['2024-01-29', 1, '2024-02-29', '1/29 もうるう年なら 2/29 まで収まる'],
    ])('%s の %d ヶ月後 → %s（%s）', (input, months, expected) => {
      expect(addMonths(d(input), months)).toBe(d(expected))
    })
  })

  it('年をまたぐ月末クランプ', () => {
    // 12/31 の2ヶ月後は 2/28（平年）
    expect(addMonths(d('2025-12-31'), 2)).toBe(d('2026-02-28'))
  })

  it('車検アラートの閾値計算として使う想定（満了日の1ヶ月前・2ヶ月前）', () => {
    const expiry = d('2026-11-30')
    expect(addMonths(expiry, -1)).toBe(d('2026-10-30'))
    expect(addMonths(expiry, -2)).toBe(d('2026-09-30'))
  })
})

describe('addYears', () => {
  const d = toDateString

  it.each([
    ['2026-09-06', 2, '2028-09-06', '通常の車検更新（+2年）'],
    ['2026-09-06', 3, '2029-09-06', '新車初回車検（+3年）'],
    ['2026-09-06', -1, '2025-09-06', '負の数で過去へ'],
    ['2026-09-06', 0, '2026-09-06', 'ゼロは変化なし'],
  ])('%s の %d 年後 → %s（%s）', (input, years, expected) => {
    expect(addYears(d(input), years)).toBe(d(expected))
  })

  describe('うるう年2/29のクランプ', () => {
    it('2/29 の2年後は平年の2月なので 2/28 にクランプ', () => {
      expect(addYears(d('2024-02-29'), 2)).toBe(d('2026-02-28'))
    })

    it('2/29 の4年後は次のうるう年なので 2/29 のまま', () => {
      expect(addYears(d('2024-02-29'), 4)).toBe(d('2028-02-29'))
    })

    it('2/29 の1年後は平年なので 2/28 にクランプ', () => {
      expect(addYears(d('2024-02-29'), 1)).toBe(d('2025-02-28'))
    })
  })
})
